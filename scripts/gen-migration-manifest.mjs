#!/usr/bin/env node
// US-2009: generate the footer-era migration manifest the edge boot guard uses.
//
// WHY A MANIFEST AT ALL. latest_schema_migration() returns a MAX watermark, and
// apply-prod-migrations.sh skips any file whose prefix is <= current. So a gap
// in the MIDDLE of the range is structurally invisible: the watermark only ever
// moves forward, and a file below it is never re-applied or re-checked. The edge
// compared a single number, which proves the head landed and proves nothing
// about anything beneath it.
//
// WHY IT STARTS AT 00254. The self-recording footer was introduced by migration
// 00254; the ~253 files below it carry no footer, so their ABSENCE from
// applied_migrations is expected and means nothing. Including them would produce
// ~253 permanent false "missing" reports, and a check that always fires is a
// check nobody reads. Everything from 00254 up is required to self-record — the
// repo has zero exceptions there — so a gap in that range is a real finding.
//
// Run: node scripts/gen-migration-manifest.mjs [--check]
//   --check exits nonzero if the committed manifest is stale (CI guard).

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const MIGRATIONS_DIR = join(root, "supabase", "migrations");
const OUT = join(root, "services", "edge-functions", "src", "lib", "migration-manifest.ts");

/** First migration that carries a self-recording footer. */
export const FOOTER_ERA_START = "00254";

function versions() {
  return readdirSync(MIGRATIONS_DIR)
    .filter((f) => f.endsWith(".sql"))
    .map((f) => f.slice(0, f.indexOf("_")))
    .filter((v) => /^\d{5}$/.test(v) && v >= FOOTER_ERA_START)
    .sort();
}

function render(list) {
  return `// GENERATED by scripts/gen-migration-manifest.mjs — do not edit by hand.
//
// US-2009: every migration from ${FOOTER_ERA_START} on carries a self-recording footer, so
// each of these MUST appear in public.applied_migrations. The boot guard checks
// the whole SET, not just the max — a mid-sequence gap is otherwise invisible,
// because the watermark only moves forward and a file below it is never
// re-applied.
//
// Regenerate with: node scripts/gen-migration-manifest.mjs
// CI fails if this drifts from supabase/migrations/ (schema-version_test.ts).

export const FOOTER_ERA_START = ${JSON.stringify(FOOTER_ERA_START)};

export const EXPECTED_MIGRATIONS: readonly string[] = ${
    JSON.stringify(list, null, 2).replace(/\n/g, "\n")
  } as const;
`;
}

const list = versions();
const next = render(list);

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    console.error("✗ migration manifest missing — run: node scripts/gen-migration-manifest.mjs");
    process.exit(1);
  }
  if (current.trim() !== next.trim()) {
    console.error(
      "✗ migration manifest is STALE. Run: node scripts/gen-migration-manifest.mjs\n" +
        "  (a migration was added or removed without regenerating the boot-guard manifest)",
    );
    process.exit(1);
  }
  console.log(`✓ migration manifest current (${list.length} footer-era migrations)`);
} else {
  writeFileSync(OUT, next);
  console.log(`✓ wrote ${list.length} footer-era migrations to ${OUT}`);
}
