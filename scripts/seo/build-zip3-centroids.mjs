// Regenerates src/lib/zip3-centroids.ts from the Census ZCTA gazetteer.
//
// SOURCE: 2020 Gazetteer, ZIP Code Tabulation Areas, national file.
//   https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2020_Gazetteer/2020_Gaz_zcta_national.zip
// Columns used: GEOID (5-digit ZCTA), ALAND_SQMI, INTPTLAT, INTPTLONG.
//
// WHY ZIP3 AND NOT ZIP5: a 5-digit table is 33,000 rows and would dominate the
// page bundle. USPS zones are assigned per 3-digit prefix area anyway, so the
// prefix is the right grain. Centroids are land-area weighted, because an
// unweighted mean lets one huge desert ZCTA drag a metro prefix into the sand.
//
// Usage: node scripts/seo/build-zip3-centroids.mjs <path-to-gazetteer.txt>
import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2];
if (!src) {
  console.error("usage: node scripts/seo/build-zip3-centroids.mjs <gazetteer.txt>");
  process.exit(1);
}

const lines = readFileSync(src, "utf8").split(/\r?\n/);
const header = lines[0].split("\t").map((h) => h.trim());
const iGeo = header.indexOf("GEOID");
const iArea = header.indexOf("ALAND_SQMI");
const iLat = header.indexOf("INTPTLAT");
const iLon = header.findIndex((h) => h.startsWith("INTPTLONG"));
if ([iGeo, iArea, iLat, iLon].some((i) => i < 0)) throw new Error("unexpected gazetteer columns");

/** prefix -> { wLat, wLon, w } */
const acc = new Map();
for (const line of lines.slice(1)) {
  if (!line.trim()) continue;
  const f = line.split("\t");
  const zip = (f[iGeo] || "").trim();
  if (!/^\d{5}$/.test(zip)) continue;
  const lat = Number(f[iLat]);
  const lon = Number(f[iLon]);
  // Land area is the weight. A water-only ZCTA weighs nothing but must not be
  // dropped outright, or a coastal prefix made of them would vanish.
  const w = Math.max(Number(f[iArea]) || 0, 0.01);
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  const p = zip.slice(0, 3);
  const cur = acc.get(p) || { wLat: 0, wLon: 0, w: 0 };
  cur.wLat += lat * w;
  cur.wLon += lon * w;
  cur.w += w;
  acc.set(p, cur);
}

const prefixes = [...acc.keys()].sort();
// Packed as one string of fixed-width records so the module stays small and
// diffable: PPP + lat*100 signed 5 chars + lon*100 signed 6 chars.
const packed = prefixes
  .map((p) => {
    const { wLat, wLon, w } = acc.get(p);
    const lat = Math.round((wLat / w) * 100);
    const lon = Math.round((wLon / w) * 100);
    return `${p}${String(lat).padStart(5, " ")}${String(lon).padStart(6, " ")}`;
  })
  .join("");

const out = `// GENERATED by scripts/seo/build-zip3-centroids.mjs — do not hand-edit.
//
// Land-area-weighted centroid of every 3-digit ZIP prefix, from the US Census
// 2020 ZCTA Gazetteer. Used to estimate a USPS zone from two ZIP codes without
// a network call (US-9004 AC2).
//
// Packed 14 chars per record: 3 prefix digits, lat*100 right-aligned in 5,
// lon*100 right-aligned in 6. ${prefixes.length} prefixes.
export const ZIP3_PACKED =
  "${packed}";

export const ZIP3_RECORD_LENGTH = 14;
export const ZIP3_COUNT = ${prefixes.length};

/** Centroid for a 3-digit prefix, or null if the prefix is not in use. */
export function zip3Centroid(prefix: string): { lat: number; lon: number } | null {
  if (!/^\\d{3}$/.test(prefix)) return null;
  // Binary search: records are sorted by prefix and fixed width.
  let lo = 0;
  let hi = ZIP3_COUNT - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const at = mid * ZIP3_RECORD_LENGTH;
    const key = ZIP3_PACKED.slice(at, at + 3);
    if (key === prefix) {
      return {
        lat: Number(ZIP3_PACKED.slice(at + 3, at + 8)) / 100,
        lon: Number(ZIP3_PACKED.slice(at + 8, at + 14)) / 100,
      };
    }
    if (key < prefix) lo = mid + 1;
    else hi = mid - 1;
  }
  return null;
}
`;

writeFileSync("src/lib/zip3-centroids.ts", out);
console.log(`[zip3] wrote src/lib/zip3-centroids.ts — ${prefixes.length} prefixes, ${packed.length} packed chars`);
