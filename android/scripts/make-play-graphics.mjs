#!/usr/bin/env node
// US-2894: build the Play listing graphics from assets that already exist in the
// repo, so the set is reproducible rather than a folder somebody once dragged
// files into.
//
//   node android/scripts/make-play-graphics.mjs [--check]
//
// Sources, and why each one:
//   icon           ios/.../AppIcon-1024.png. The same mark ships on both stores;
//                  drawing a second one is how the two drift apart. Its rounded
//                  corners are baked in against white, and Play rounds the icon
//                  again, so the corners are re-cut as alpha and laid on navy.
//   feature        composed here from public/logo_white.png. No screenshot, no
//                  price, no rating, no Play badge - Play polices all four.
//   screenshots    android/app/src/test/screenshots/*.png. These are Roborazzi
//                  renders of the real Composables with the real fixture data,
//                  at 1080x2340, which is a phone. They are truer than a staged
//                  capture and they are regenerated by the same lane that
//                  guards them.
//
// Play caps a screenshot's aspect ratio at 2:1 and a 1080x2340 render is
// 2.167:1, so each one is cropped to the top 1080x2160. The crop takes the
// bottom 180px, which on every screen chosen here is padding below the last
// control.

import { mkdirSync, readFileSync, existsSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = join(REPO, "android/fastlane/metadata/android/en-US/images");
const GOLDENS = join(REPO, "android/app/src/test/screenshots");

const NAVY = { r: 0x0f, g: 0x34, b: 0x60, alpha: 1 };

// Roborazzi render size, and the Play-legal crop taken from the top of it.
const SHOT_W = 1080;
const SHOT_H = 2340;
const CROP_H = 2160;

// The storyline from PLAY_STORE_SUBMISSION.md section 2, in the order Play
// shows them. The first two are what most browsers ever see.
const PHONE_SHOTS = [
  ["1_today.png", "screen-home-light.png"],
  ["2_ai_fill.png", "screen-aifill-both-light.png"],
  ["3_grade_report.png", "screen-gradereport-pristine-light.png"],
  ["4_list_on_ebay.png", "screen-publish-ready-light.png"],
  ["5_money.png", "screen-money-populated-light.png"],
  ["6_inventory.png", "screen-inventory-list-light.png"],
];

// DELIBERATELY EMPTY until US-2905 lands. The tablet goldens render today's
// tablet layout, which is the phone layout with a rail down the side: the right
// half of a 2560x1600 frame is blank, the charts have nothing in them and the
// visible copy is "No completed sales yet". Shipping that costs more than the
// "not designed for tablets" notice it would remove. Re-add the two entries
// once the two-pane layout exists and regenerate.
const TABLET_SHOTS = [];

function log(line) {
  process.stdout.write(line + "\n");
}

async function buildIcon() {
  const src = join(REPO, "ios/GradeThread/Assets.xcassets/AppIcon.appiconset/AppIcon-1024.png");
  // The source's corner radius measures ~180/1024. Re-cutting it at the same
  // ratio drops the white corners without touching the mark, and the mask is
  // inset 8px because a mask laid exactly on the source's own edge keeps that
  // edge's anti-aliased white pixels and they read as a hairline halo.
  const INSET = 8;
  const radius = Math.round(512 * (180 / 1024));
  const mask = Buffer.from(
    `<svg width="512" height="512"><rect x="${INSET}" y="${INSET}" width="${512 - INSET * 2}" height="${512 - INSET * 2}" rx="${radius - INSET}" ry="${radius - INSET}" fill="#fff"/></svg>`,
  );
  const rounded = await sharp(src)
    .resize(512, 512, { fit: "cover" })
    .composite([{ input: mask, blend: "dest-in" }])
    .png()
    .toBuffer();

  // Flatten onto navy so the delivered file has no alpha at all: Play accepts
  // alpha and then composites it against a background nobody here chose.
  await sharp({ create: { width: 512, height: 512, channels: 4, background: NAVY } })
    .composite([{ input: rounded }])
    .flatten({ background: NAVY })
    .png({ compressionLevel: 9 })
    .toFile(join(OUT, "icon.png"));

  return "icon.png";
}

async function buildFeatureGraphic() {
  const logo = join(REPO, "public/logo_white.png");
  // logo_white.png is 1806x376 and carries a navy icon tile on its left that
  // would vanish against a navy field. Take the wordmark only.
  // trim() drops the transparent padding baked into the logo file; without it
  // the wordmark and the tagline sit a visible gap apart with nothing between.
  // Two passes on purpose: sharp runs trim BEFORE extract in one pipeline, so
  // chaining them crops the wrong rectangle and fails with "bad extract area".
  const cropped = await sharp(logo)
    .extract({ left: 340, top: 0, width: 1806 - 340, height: 376 })
    .png()
    .toBuffer();
  const wordmark = await sharp(cropped).trim().resize({ width: 600 }).png().toBuffer();
  const wordmarkHeight = (await sharp(wordmark).metadata()).height;

  const tagline = Buffer.from(
    `<svg width="1024" height="60" xmlns="http://www.w3.org/2000/svg">
       <text x="512" y="40" text-anchor="middle"
             font-family="Inter, 'Segoe UI', Arial, sans-serif"
             font-size="30" font-weight="400" fill="#C8D3E4">
         Condition grades and AI listings for resellers
       </text>
     </svg>`,
  );

  // Centre the wordmark and the tagline as one block, not the wordmark alone.
  const TAGLINE_BOX = 60;
  const GAP = 18;
  const logoTop = Math.round((500 - (wordmarkHeight + GAP + TAGLINE_BOX)) / 2);

  await sharp({ create: { width: 1024, height: 500, channels: 4, background: NAVY } })
    .composite([
      { input: wordmark, top: logoTop, left: Math.round((1024 - 600) / 2) },
      { input: tagline, top: logoTop + wordmarkHeight + GAP, left: 0 },
    ])
    .flatten({ background: NAVY })
    .png({ compressionLevel: 9 })
    .toFile(join(OUT, "featureGraphic.png"));

  return "featureGraphic.png";
}

async function buildShots(pairs, outDir, crop) {
  mkdirSync(outDir, { recursive: true });
  const written = [];
  for (const [name, golden] of pairs) {
    const src = join(GOLDENS, golden);
    if (!existsSync(src)) throw new Error(`missing golden: ${golden}`);
    let pipeline = sharp(src);
    if (crop) {
      const meta = await pipeline.metadata();
      if (meta.width !== SHOT_W || meta.height !== SHOT_H) {
        throw new Error(`${golden} is ${meta.width}x${meta.height}, expected ${SHOT_W}x${SHOT_H}`);
      }
      pipeline = pipeline.extract({ left: 0, top: 0, width: SHOT_W, height: CROP_H });
    }
    await pipeline.flatten({ background: "#ffffff" }).png({ compressionLevel: 9 }).toFile(join(outDir, name));
    written.push(name);
  }
  return written;
}

async function main() {
  mkdirSync(OUT, { recursive: true });

  const icon = await buildIcon();
  const feature = await buildFeatureGraphic();
  const phone = await buildShots(PHONE_SHOTS, join(OUT, "phoneScreenshots"), true);
  const tablet = await buildShots(TABLET_SHOTS, join(OUT, "tenInchScreenshots"), false);

  for (const rel of [icon, feature, ...phone.map((n) => `phoneScreenshots/${n}`), ...tablet.map((n) => `tenInchScreenshots/${n}`)]) {
    const path = join(OUT, rel);
    const meta = await sharp(path).metadata();
    const kb = Math.round(statSync(path).size / 1024);
    log(`${String(meta.width).padStart(4)}x${String(meta.height).padEnd(4)} ${String(kb).padStart(4)}KB  ${rel}`);
  }

  log("\nPlay limits: icon 512x512 under 1MB, feature 1024x500, screenshots 320-3840px per side, at most 2:1.");
}

main().catch((error) => {
  process.stderr.write(`\n${error.message}\n`);
  process.exit(1);
});
